def trace_key(pt: SweepPoint) -> tuple[int, int, bool, int]:
    return (pt.tp, pt.pp, pt.sp, pt.mbs)


def _has_trace(path: Path) -> bool:
    """True if the directory holds actual rank traces (an OOM'd gen leaves it empty)."""
    d = REPO_ROOT / path
    return d.is_dir() and any(d.glob("trace_rank_*.json"))


def find_trace_dir(pt: SweepPoint) -> Optional[Path]:
    """Return the trace directory for this point, or None if not available.

    Preference order:
      1. unified single-session trace, exact (tp, pp, sp, mbs, rc) — includes NATIVE
         recompute traces, so rc=true points become trace-driven when one exists;
      2. unified, same (tp, pp, sp, rc) at another mbs — mbs extrapolation applies;
      3. legacy per-session trace, exact then any-mbs (rc=false points only).

    VPP still has no trace form (interleaving changes the schedule, not the kernels
    the tracer records per-slot); it is modeled structurally in _simulate_vpp_point.
    """
    if pt.vpp is not None:
        return None
    key = (pt.tp, pt.pp, pt.sp, pt.mbs, pt.recompute)
    uni = TRACE_REGISTRY_UNIFIED.get(key)
    if uni is not None and _has_trace(uni):
        return uni
    for (tp, pp, sp, _mbs, rc), path in TRACE_REGISTRY_UNIFIED.items():
        if (tp, pp, sp, rc) == (pt.tp, pt.pp, pt.sp, pt.recompute) and _has_trace(path):
            return path  # different mbs — extrapolation will be applied
    if pt.recompute:
        return None  # no native rc trace -> constant-based fallback in simulate_point
    exact = TRACE_REGISTRY.get((pt.tp, pt.pp, pt.sp, pt.mbs))
    if exact is not None and _has_trace(exact):
        return exact
    for (tp, pp, sp, _mbs), path in TRACE_REGISTRY.items():
        if tp == pt.tp and pp == pt.pp and sp == pt.sp and _has_trace(path):
            return path
    return None


