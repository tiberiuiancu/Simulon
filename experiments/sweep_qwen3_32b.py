# ---------------------------------------------------------------------------
# Micro-batch (and TP) GEMM-efficiency correction.
#
# WHY THIS EXISTS.  Increasing mbs (or lowering TP) makes each GEMM larger and more
# tensor-core efficient, so per-token compute drops. Hardware (val40, mean iters 21-40)
# shows mbs1->mbs2 = -14.2% (PP2) / -13.4% (PP4). The trace-driven sim only sees
# -2.4% / -3.6%, because the fake-PG wall-clock SPAN it consumes pads every kernel with a
# CPU-launch idle gap that does NOT shrink when the GEMM gets more efficient. The
# kernel-timing experiment (job 1006909, SIMULON_TRACE_KERNEL_TIME=1) proved this: pure
# kernel_device_ms drops -25.8% mbs1->mbs2 while the span is flat (-1.3%).
#
# THE CORRECTION (trace-derived, NO hardcoded constant).  Decompose the trace's compute
# into pure kernel time plus overhead:  overhead(cfg) = span_compute(cfg) - kernel_compute(cfg),
# both MEASURED (span from wall-clock gaps, kernel from metadata.kernel_device_ms). The
# only defect is that the fake-PG overhead GROWS with mbs while on hardware it is ~constant
# (verified: kernel_frac * kernel_drop ~= -13% ~= the measured iteration drop). So we hold
# the overhead at its mbs=1 value and remove only the fake-PG EXCESS:
#     iter(mbs) = iter_span(mbs) - [overhead(mbs) - overhead(mbs=1)]
# Every term is a trace measurement; there is no fitted latency. Verified on tp4pp4:
# mbs2 +17.1% -> +8.0%, scaling -3.6% -> -11.1% (hardware -13.4%). Needs kernel-timing
# traces (TRACE_REGISTRY_KERNELTIME) for both the mbs and its mbs=1 anchor; where those
# are absent the point is left on the span (honestly uncorrected) unless the hardcoded
# fallback below is explicitly enabled.
#
# HARDCODED FALLBACK (OFF by default).  Before the kernel-timing traces existed the mbs
# axis was corrected by a fitted amortization law iter(mbs)=iter_sim(mbs1)-c*(1-1/mbs),
# c=2628 ms (PP-invariant fit of the two hardware points). c is a hardcoded latency
# interval, which we do NOT want in the model, so it is disabled. Kept only so the axis
# can be spot-checked if a kernel trace is unavailable; enable at your own risk.
MBS_AMORTIZATION_C = 2628.0        # ms; hardcoded fit, fallback only
MBS_AMORTIZATION_FALLBACK = False  # keep OFF: no hardcoded interval in the live model

