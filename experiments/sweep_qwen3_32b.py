# When True, PP={1,2} configs with no trace (OOM) are filled by deriving a trace
# from the tp{tp}pp4 source via pp_synth. Off by default so the production sweep
# never silently includes unvalidated numbers. Set by main() from --derive-low-pp.
DERIVE_LOW_PP = False
DERIVED_CACHE_DIR = Path("results/derived_traces")
_derived_cache: dict[tuple[int, int, bool], Path] = {}


def _derive_low_pp_trace(pt: SweepPoint) -> tuple[Optional[Path], Optional[str]]:
    """Derive a PP={1,2} trace from the tp{tp}pp4 source; return (dir, note) or (None, None).

    The derived trace is cached per (tp, pp, sp) and built at the mbs=1 microbatch
    count (the largest); mbs-extrapolation trims it for higher mbs.
    """
    if not DERIVE_LOW_PP or pt.pp not in (1, 2):
        return None, None
    src = TRACE_REGISTRY.get((pt.tp, 4, pt.sp, 1))
    if src is None or not (REPO_ROOT / src / "trace_rank_0.json").exists():
        return None, None
    key = (pt.tp, pt.pp, pt.sp)
    if key not in _derived_cache:
        from simulon.backend.dag.pp_synth import derive_pp_from_dir
        dp = pt.num_gpus // (pt.tp * pt.pp)
        n_mb = max(8, GLOBAL_BATCH_SIZE // dp)  # mbs=1 count
        dest = DERIVED_CACHE_DIR / f"tp{pt.tp}pp{pt.pp}sp{'true' if pt.sp else 'false'}"
        derive_pp_from_dir(src, dest, src_pp=4, target_pp=pt.pp, num_microbatches=n_mb)
        _derived_cache[key] = dest
    note = (f"DERIVED trace (pp_synth: PP{pt.pp} from tp{pt.tp}pp4) — "
            "UNVALIDATED, gate with validate_pp_derive.py")
    return _derived_cache[key], note


def build_scenario(pt: SweepPoint, traces_dir: Path) -> ScenarioConfig:
    base_cfg = yaml.safe_load(BASE_WORKLOAD.read_text())["config"]
    cfg = copy.deepcopy(base_cfg)

    cfg["num-gpus"] = pt.num_gpus
    cfg["tensor-model-parallel-size"] = pt.tp
    cfg["pipeline-model-parallel-size"] = pt.pp
    cfg["sequence-parallel"] = pt.sp
    cfg["recompute-activations"] = pt.recompute
    cfg["micro-batch-size"] = pt.mbs
    cfg["global-batch-size"] = GLOBAL_BATCH_SIZE

    if pt.vpp is not None:
        cfg["num-layers-per-virtual-pipeline-stage"] = pt.vpp
    else:
        cfg.pop("num-layers-per-virtual-pipeline-stage", None)

    dc = DatacenterConfig.model_validate({
        "num_nodes": pt.num_nodes,
        "node": JUPITER_NODE,
    })
    wl = MegatronWorkload.model_validate({
        "framework": "megatron",
        "config": cfg,
        "traces_dir": str(traces_dir),
    })
    return ScenarioConfig(datacenter=dc, workload=wl)


@dataclass
class SimResult:
    pt: SweepPoint
    status: str           # "ok" | "no_trace" | "oom" | "error"
    traces_dir: Optional[str] = None
    error: Optional[str] = None
    total_ms: float = 0.0
    compute_ms: float = 0.0
    exposed_comm_ms: float = 0.0
    bubble_ms: float = 0.0
    per_gpu_tps: float = 0.0
    per_gpu_tflops: Optional[float] = None
    mfu_pct: Optional[float] = None
    mem_peak_gb: Optional[float] = None
    mem_fits: Optional[bool] = None
    # Exposed PP_Send+PP_Recv time from the DAG replay's comm model. Carried so the
    # VPP model can price interleaving's extra p2p messages with the SAME modeled
    # per-message cost the base simulation used (no hardcoded latencies).
    pp_exposed_ms: Optional[float] = None
    # Pipeline-stage load-imbalance idle for the average GPU: max(per-GPU compute)
    # - mean(per-GPU compute), from the DAG. The bubble_ms residual is imbalance +
    # warmup/drain; this separates them so VPP only gets credit for the part
    # interleaving can actually remove (warmup/drain, NOT imbalance).
    imbalance_ms: Optional[float] = None
    # mbs GEMM-efficiency correction applied to total_ms (ms; positive = made faster).
    # 0.0 for mbs=1 or when no correction fired.
    mbs_correction_ms: float = 0.0
    # How the correction was derived: "kernel-trace" (trace-measured overhead, preferred,
    # no hardcode), "amortization-fallback" (hardcoded c, only if explicitly enabled), or
    # "none" (left on the span -- honestly uncorrected).
    mbs_correction_method: str = "none"

    def to_dict(self) -> dict:
        pt = self.pt
        return {
            "tp": pt.tp, "pp": pt.pp, "sp": pt.sp,
            "recompute": pt.recompute, "mbs": pt.mbs,
            "vpp": pt.vpp, "num_nodes": pt.num_nodes,
            "dp": pt.dp, "grad_accum_steps": pt.grad_accum_steps,
            "status": self.status, "error": self.error,
            "traces_dir": self.traces_dir,
            "total_ms": self.total_ms, "compute_ms": self.compute_ms,
            "exposed_comm_ms": self.exposed_comm_ms, "bubble_ms": self.bubble_ms,
            "mbs_correction_ms": self.mbs_correction_ms,
            "mbs_correction_method": self.mbs_correction_method,
            "per_gpu_tps": self.per_gpu_tps,
            "per_gpu_tflops": self.per_gpu_tflops,
            "mfu_pct": self.mfu_pct,
            "mem_peak_gb": self.mem_peak_gb,
            "mem_fits": self.mem_fits,
        }


def _simulate_vpp_point(pt: SweepPoint) -> SimResult:
    """Predict a VPP config from its non-VPP base, STRUCTURALLY (no fitted constants).

    Interleaved 1F1B with ``v`` virtual chunks per device changes two things, both
    derivable from quantities the base simulation already computed:

    1. BUBBLE: the warmup/drain bubble shrinks by 1/v — but ONLY the analytic
       warmup/drain portion ``(pp-1)/n_mb`` of the base bubble. The rest of the
       base bubble is pipeline-stage load imbalance (e.g. the 262k-vocab LM head on
       the last stage: 42% imbalance at PP=4), which interleaving does not remove
       in a way our non-interleaved traces can attest — so no credit is taken.

    2. EXTRA P2P: with v chunks per device, every microbatch crosses each stage
       boundary v times instead of once, in both directions. Message COUNT scales
       by v at unchanged message size, so the added cost is
           (v - 1) x (base exposed PP_Send+PP_Recv time)
       priced by the SAME comm model that produced the base p2p time — measured
       NCCL curves, not a hardcoded latency. With overlap_p2p_comm=false (required
       to match the traces; also what makes VPP illegal at PP<=2) these sends are
       synchronous, so counting them as exposed is structurally right.

    Validation (16n, TP4/PP4/mbs2, v=4, jobs 977878/977882): measured +5.2..+13.2%
    slowdown depending on statistic (midpoint +6.2%); this model's prediction is
    printed by the sweep — check against fresh v40 measurements when they land.
    """
    base = SweepPoint(
        tp=pt.tp, pp=pt.pp, sp=pt.sp, recompute=pt.recompute,
        mbs=pt.mbs, vpp=None, num_nodes=pt.num_nodes,
    )
    base_res = simulate_point(base)
    if base_res.status != "ok":
        return SimResult(pt=pt, status=base_res.status,
                         traces_dir=base_res.traces_dir, error=base_res.error)

    v = pt.num_layers // (pt.pp * pt.vpp)  # virtual chunks per device
    n_mb = pt.grad_accum_steps
    nonbubble = base_res.total_ms - base_res.bubble_ms

    note = None
    if pt.pp <= 1 or v <= 1 or n_mb <= 0:
        total_vpp = base_res.total_ms  # degenerate: no interleaving
    else:
        # Bubble decomposition, all from the base DAG: bubble = stage-imbalance idle
        # + warmup/drain idle. Interleaving can only shrink the warmup/drain part
        # (by 1/v); the imbalance part (dominated by the 262k-vocab LM head on the
        # last stage) stays. At PP4 the imbalance is ~94% of the bubble, which is
        # why the analytic (pp-1)/n_mb credit alone over-predicted VPP badly.
        warmup_bubble = max(0.0, base_res.bubble_ms - (base_res.imbalance_ms or 0.0))
        warmup_bubble = min(warmup_bubble,
                            (pt.pp - 1) / n_mb * base_res.total_ms)  # analytic cap
        recovered = warmup_bubble * (1.0 - 1.0 / v)
        extra_p2p = (v - 1) * (base_res.pp_exposed_ms or 0.0)
        total_vpp = base_res.total_ms - recovered + extra_p2p
        note = (f"VPP v={v}: structural model — recovers {recovered:.0f} ms warmup "
                f"bubble (imbalance {base_res.imbalance_ms or 0:.0f} ms not "
                f"recoverable), adds {extra_p2p:.0f} ms extra p2p "
                f"((v-1) x modeled PP p2p cost)")

    speedup = base_res.total_ms / total_vpp if total_vpp > 0 else 1.0
    return SimResult(
        pt=pt, status="ok", traces_dir=base_res.traces_dir, error=note,
        total_ms=total_vpp,
        compute_ms=base_res.compute_ms,
        exposed_comm_ms=base_res.exposed_comm_ms,
        bubble_ms=max(0.0, total_vpp - nonbubble),
        per_gpu_tps=base_res.per_gpu_tps * speedup,
        per_gpu_tflops=(base_res.per_gpu_tflops * speedup
                        if base_res.per_gpu_tflops is not None else None),
        mfu_pct=(base_res.mfu_pct * speedup if base_res.mfu_pct is not None else None),
    )


def _simulate_recompute_point(pt: SweepPoint) -> SimResult:
    """Predict a selective-recompute config from its no-recompute base.

    Selective recompute re-runs the core attention in the backward pass; the
    extra work is serial compute that adds to wall time. We model it as a
    multiplier on the base compute (``SELECTIVE_RECOMPUTE_COMPUTE_OVERHEAD``),
    calibrated from one measured run — the recomputed core-attention cost cannot
    be isolated from the projection GEMMs in the trace.

    Throughput / TFLOPs / MFU all drop proportionally with the added wall time:
    selective recompute does not change the model FLOP count Megatron reports, so
    the same useful work simply takes longer.

    Composes with VPP: a recompute+VPP point routes here first (extra compute),
    then the VPP bubble correction is applied on top via the base lookup.
    """
    base = SweepPoint(
        tp=pt.tp, pp=pt.pp, sp=pt.sp, recompute=False,
        mbs=pt.mbs, vpp=pt.vpp, num_nodes=pt.num_nodes,
    )
    base_res = simulate_point(base)
    if base_res.status != "ok":
        return SimResult(pt=pt, status=base_res.status,
                         traces_dir=base_res.traces_dir, error=base_res.error)

    overhead_ms = SELECTIVE_RECOMPUTE_COMPUTE_OVERHEAD * base_res.compute_ms
    total = base_res.total_ms + overhead_ms
    slow = base_res.total_ms / total if total > 0 else 1.0
    note = None if RECOMPUTE_CALIBRATED else "uncalibrated recompute factor"
    return SimResult(
        pt=pt, status="ok", traces_dir=base_res.traces_dir, error=note,
        total_ms=total,
        compute_ms=base_res.compute_ms + overhead_ms,
        exposed_comm_ms=base_res.exposed_comm_ms,
        bubble_ms=base_res.bubble_ms,
        per_gpu_tps=base_res.per_gpu_tps * slow,
        per_gpu_tflops=(base_res.per_gpu_tflops * slow
                        if base_res.per_gpu_tflops is not None else None),
        mfu_pct=(base_res.mfu_pct * slow if base_res.mfu_pct is not None else None),
        pp_exposed_ms=base_res.pp_exposed_ms,
    )


def _kernel_compute_ms(pt: SweepPoint) -> Optional[float]:
    """compute_ms from this config's KERNEL-TIMING trace, i.e. the DAG built with
    metadata.kernel_device_ms wired in (compute_scale in trace_tracer.py). Pure GPU kernel
    time, fake-PG idle removed. None if no kernel-timing trace exists for the config."""
    key = (pt.tp, pt.pp, pt.sp, pt.mbs, pt.recompute)
    td = TRACE_REGISTRY_KERNELTIME.get(key)
    if td is None or not _has_trace(td):
        return None
    try:
        _, r = run_simulation(build_scenario(pt, td))
        return r.compute_ms
    except Exception:
        return None


def _finish_correction(raw: SimResult, corrected: float, saving: float,
                       method: str) -> SimResult:
    """Rebuild an ok result with total_ms=corrected; attribute the saving to compute (it is
    a compute-kernel efficiency effect) so compute+comm+bubble still sums to total, and
    scale throughput/MFU inversely with the new total."""
    if corrected <= 0 or raw.total_ms <= 0:
        return raw
    scale = raw.total_ms / corrected  # throughput ∝ 1/total
    return replace(
        raw,
        total_ms=corrected,
        compute_ms=max(0.0, corrected - raw.exposed_comm_ms - raw.bubble_ms),
        per_gpu_tps=raw.per_gpu_tps * scale,
        per_gpu_tflops=(raw.per_gpu_tflops * scale) if raw.per_gpu_tflops is not None else None,
        mfu_pct=(raw.mfu_pct * scale) if raw.mfu_pct is not None else None,
        mbs_correction_ms=saving,
        mbs_correction_method=method,
    )


def _apply_gemm_efficiency(pt: SweepPoint, raw: SimResult) -> SimResult:
    """Correct the mbs- AND TP-GEMM-efficiency of a trace-driven result. Both axes share
    one mechanism: bigger GEMMs (higher mbs, lower TP) run more tensor-core efficient, the
    fake-PG wall-clock SPAN can't see it, but the measured per-kernel device time can.

    PREFERRED path is fully trace-derived (no hardcoded constant). Replace the config's
    span compute with pure kernel time plus the launch/dispatch OVERHEAD held at a single
    VALIDATED reference -- the tp4/mbs=1 config at the same pp (span matches hardware
    +5-7%):
        overhead_ref = span_compute(tp4,mbs1) - kernel_compute(tp4,mbs1)
        compute(cfg) = kernel_compute(cfg) + overhead_ref
        iter(cfg)    = total - span_compute(cfg) + compute(cfg)
    The reference IS the config when pt is already tp4/mbs1, so those points are untouched.
    Every term is a trace measurement; there is no fitted latency. Needs kernel-timing
    traces for the config and the reference; if either is missing the point is left on the
    span (method="none") unless the mbs-only hardcoded fallback is explicitly enabled.
    SP=true is never corrected -- its traces are invalid under fake-PG."""
    if raw.status != "ok" or pt.sp:
        return raw
    ref_pt = replace(pt, tp=4, mbs=1)  # validated anchor; tp4/mbs1 => no recursion here
    if ref_pt == pt:
        return raw  # this config IS the reference -> nothing to correct

    # --- Preferred: trace-derived kernel + reference overhead (no hardcoded interval) ---
    k_cfg = _kernel_compute_ms(pt)
    k_ref = _kernel_compute_ms(ref_pt)
    ref = simulate_point(ref_pt)
    if k_cfg is not None and k_ref is not None and ref.status == "ok":
        overhead_ref = ref.compute_ms - k_ref          # validated launch/dispatch overhead
        corrected_compute = k_cfg + overhead_ref
        corrected_total = raw.total_ms - raw.compute_ms + corrected_compute
        saving = raw.total_ms - corrected_total
        return _finish_correction(raw, corrected_total, saving, "kernel-trace")

    # --- Fallback: hardcoded mbs amortization law (OFF by default; mbs axis only) -------
    if MBS_AMORTIZATION_FALLBACK and pt.mbs > 1:
        base = simulate_point(replace(pt, mbs=1))
        if base.status == "ok" and base.total_ms > 0:
            saving = MBS_AMORTIZATION_C * (1.0 - 1.0 / pt.mbs)
            return _finish_correction(raw, base.total_ms - saving, saving,
                                      "amortization-fallback")

    note = "gemm-efficiency correction skipped: no kernel-timing trace (on span)"
    return replace(raw, error=_join_notes(raw.error, note))


def _join_notes(a: Optional[str], b: str) -> str:
    return f"{a}; {b}" if a else b


def simulate_point(pt: SweepPoint) -> SimResult:
    if pt.vpp is not None:
        return _simulate_vpp_point(pt)
    if pt.recompute and find_trace_dir(pt) is None:
        # No NATIVE recompute trace for this cell — fall back to the fitted
        # compute-multiplier model. When a native rc trace exists (unified registry)
        # the point flows through the normal trace-driven path instead, with the
        # recomputed backward kernels actually measured.
        return _simulate_recompute_point(pt)

    traces_dir = find_trace_dir(pt)

    derive_note = None
    if traces_dir is None:
        traces_dir, derive_note = _derive_low_pp_trace(pt)

    if traces_dir is None:
        return SimResult(pt=pt, status="no_trace",
                         traces_dir=str(TRACE_REGISTRY.get(trace_key(pt), "")))

    try:
        sc = build_scenario(pt, traces_dir)
        dag, result = run_simulation(sc)
        gpu_spec = resolve_gpu_spec(sc.datacenter)

        mem_peak_gb = mem_fits = None
        if gpu_spec.memory_capacity_gb is not None:
            est = estimate_memory(sc.workload.config, pt.num_gpus,
                                  gpu_spec.memory_capacity_gb)
            mem_peak_gb, mem_fits = round(est.peak_gb, 1), est.fits

        tokens = (sc.workload.config.get("global-batch-size", 0)
                  * sc.workload.config.get("seq-length", 0))
        n_gpus = len(result.per_gpu_times_ms) or 1
        tps = tokens / (result.total_time_ms / 1000.0) if result.total_time_ms > 0 else 0.0
        per_gpu_tps = tps / n_gpus

        per_gpu_tflops = None
        mfu_pct = None
        if result.total_flops is not None and tokens > 0:
            gflops_per_token = result.total_flops / tokens / 1e9
            tflops_total = tps * gflops_per_token / 1e3
            per_gpu_tflops = tflops_total / n_gpus
            if gpu_spec.peak_tflops_bf16 is not None:
                mfu_pct = (per_gpu_tflops / gpu_spec.peak_tflops_bf16) * 100

        # A config that cannot fit in GPU memory must never be RANKED, however fast the
        # simulator thinks it is -- otherwise the sweep happily reports an optimum that
        # OOMs on hardware. Measured 2026-07-19: TP4 mbs=4 OOMs at both PP=2 and PP=4
        # (real CUDA OOM, 92.74 GiB allocated), including with recompute, while the
        # simulator rated it a perfectly good 10848 ms.
        # Note such configs can present as a p2p HANG rather than a clean OOM: on GH200
        # an oversubscribed allocation can be backed by host memory over NVLink-C2C.
        if mem_fits is False:
            return SimResult(
                pt=pt, status="oom", traces_dir=str(traces_dir),
                error=f"predicted peak {mem_peak_gb} GB > "
                      f"{gpu_spec.memory_capacity_gb} GB capacity",
                mem_peak_gb=mem_peak_gb, mem_fits=mem_fits,
            )

        pp_exposed = sum(v for k, v in (result.exposed_comm_by_type or {}).items()
                         if k in ("PP_Send", "PP_Recv"))

        # Stage-imbalance idle: how much the average GPU waits on the busiest one.
        per_gpu_busy: dict[int, float] = {}
        for n in dag.compute_nodes:
            per_gpu_busy[n.gpu_rank] = per_gpu_busy.get(n.gpu_rank, 0.0) + n.duration_ms
        imbalance = 0.0
        if per_gpu_busy:
            vals = list(per_gpu_busy.values())
            imbalance = max(vals) - sum(vals) / len(vals)

        raw = SimResult(
            pt=pt, status="ok", traces_dir=str(traces_dir), error=derive_note,
            total_ms=result.total_time_ms,
            compute_ms=result.compute_ms,
            exposed_comm_ms=result.exposed_comm_ms,
            bubble_ms=result.bubble_ms,
            per_gpu_tps=per_gpu_tps,
            per_gpu_tflops=per_gpu_tflops,
            mfu_pct=mfu_pct,
            mem_peak_gb=mem_peak_gb,
            mem_fits=mem_fits,
            pp_exposed_ms=pp_exposed,
            imbalance_ms=imbalance,
        )
        return _apply_gemm_efficiency(pt, raw)
    except Exception as exc:
        return SimResult(pt=pt, status="error",
                         traces_dir=str(traces_dir), error=str(exc))


