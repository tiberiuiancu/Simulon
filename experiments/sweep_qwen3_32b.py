def _pct(part: float, total: float) -> str:
    return f"{part / total * 100:4.1f}%" if total > 0 else "  n/a"


def print_table(results: list[SimResult]) -> None:
    ok = [r for r in results if r.status == "ok"]
    skipped = [r for r in results if r.status == "no_trace"]
    oom = [r for r in results if r.status == "oom"]
    errors = [r for r in results if r.status == "error"]

    ok.sort(key=lambda r: r.per_gpu_tps, reverse=True)

    hdr = (
        f"{'TP':>2}  {'PP':>2}  {'SP':>5}  {'RC':>5}  {'MBS':>3}  {'VPP':>4}  {'Nodes':>5}  "
        f"{'iter ms':>8}  {'tps/GPU':>8}  {'TFLOPs':>7}  {'MFU%':>5}  "
        f"{'comm%':>5}  {'bbl%':>4}"
    )
    sep = "─" * len(hdr)
    print(f"\n{'Simulon sweep — Qwen3-32B on Jupiter GH200':^{len(hdr)}}")
    print(sep)
    print(hdr)
    print(sep)
    for r in ok:
        pt = r.pt
        tflops_s = f"{r.per_gpu_tflops:7.1f}" if r.per_gpu_tflops is not None else "      -"
        mfu_s = f"{r.mfu_pct:5.1f}" if r.mfu_pct is not None else "    -"
        comm_pct = _pct(r.exposed_comm_ms, r.total_ms)
        bbl_pct = _pct(r.bubble_ms, r.total_ms)
        print(
            f"{pt.tp:>2}  {pt.pp:>2}  {str(pt.sp):>5}  {str(pt.recompute):>5}  "
            f"{pt.mbs:>3}  {_vpp_display(pt):>4}  {pt.num_nodes:>5}  "
            f"{r.total_ms:8.1f}  {r.per_gpu_tps:8.1f}  {tflops_s}  {mfu_s}  "
            f"{comm_pct}  {bbl_pct}"
        )
    print(sep)
    print(f"  {len(ok)} configs simulated, {len(skipped)} need traces, "
          f"{len(oom)} excluded (OOM), {len(errors)} errors\n")

    if oom:
        # Listed explicitly rather than silently dropped: "this config is fast but does
        # not fit" is a useful answer, and hiding it invites someone to re-add it later.
        print("Excluded — predicted to exceed GPU memory (verified against 13/13 measured")
        print("fit/OOM points at 16 nodes; see VALIDATION_16N.md §3):")
        for r in sorted(oom, key=lambda r: (r.pt.num_nodes, r.pt.tp, r.pt.pp, r.pt.mbs)):
            pt = r.pt
            print(f"    tp{pt.tp} pp{pt.pp} mbs{pt.mbs} rc={pt.recompute} "
                  f"vpp={_vpp_display(pt)} {pt.num_nodes}n — {r.error}")
        print()

    if skipped:
        print("Configs needing trace generation (run on a Jupiter node with a GH200 GPU):")
        print()
        seen: set[tuple] = set()
        workload_dir = Path("experiments/sweep_qwen3_32b_workloads")
        workload_dir.mkdir(parents=True, exist_ok=True)
        base_cfg = yaml.safe_load(BASE_WORKLOAD.read_text())

        for r in skipped:
            pt = r.pt
            key = (pt.tp, pt.pp, pt.sp, pt.recompute, pt.mbs, pt.vpp)
            if key in seen:
                continue
            seen.add(key)

            cfg = copy.deepcopy(base_cfg["config"])
            cfg["num-gpus"] = pt.tp * pt.pp * 8  # 8 DP = reasonable trace world size
            cfg["tensor-model-parallel-size"] = pt.tp
            cfg["pipeline-model-parallel-size"] = pt.pp
            cfg["sequence-parallel"] = pt.sp
            cfg["recompute-activations"] = pt.recompute
            cfg["micro-batch-size"] = pt.mbs
            # global-batch-size: keep grad_accum=8 for trace generation
            cfg["global-batch-size"] = pt.mbs * 8 * pt.tp * pt.pp
            if pt.vpp is not None:
                cfg["num-layers-per-virtual-pipeline-stage"] = pt.vpp
            else:
                cfg.pop("num-layers-per-virtual-pipeline-stage", None)

            sp_str = "sp" if pt.sp else "no-sp"
            rc_str = "rc" if pt.recompute else "no-rc"
            vpp_str = f"-vpp{pt.vpp}" if pt.vpp else ""
            fname = f"tp{pt.tp}-pp{pt.pp}-{sp_str}-{rc_str}-mbs{pt.mbs}{vpp_str}.yaml"
            wl_path = workload_dir / fname
            with open(wl_path, "w") as f:
                yaml.dump({"framework": "megatron", "config": cfg}, f,
                          default_flow_style=False, sort_keys=False)

            print(f"  {fname}")
            print(f"    python -c \"from simulon.cli import app; app(['trace', 'generate', "
                  f"'{wl_path}', '--gpu', 'gh200_jupiter'])\"")
            print()

        print(f"  Workload files written to {workload_dir}/\n")

    if errors:
        print("Errors:")
        for r in errors:
            print(f"  {r.pt.label()}: {r.error}")
        print()


