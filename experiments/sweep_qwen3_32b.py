#     TP4/PP2/mbs1/gbs256/16n SP=false, recompute  11,076.0 ms  (job 977786)
#     TP4/PP2/mbs1/gbs256/16n SP=false, baseline   10,636.0 ms  (measured)
#     overhead = 11076.0/10636.0 - 1 = +4.14% wall
