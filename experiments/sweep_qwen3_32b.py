@dataclass(frozen=True)
class SweepPoint:
    tp: int
    pp: int
    sp: bool            # sequence-parallel (requires TP > 1)
    recompute: bool     # recompute-activations
    mbs: int            # micro-batch-size
    vpp: Optional[int]  # num_layers_per_virtual_pipeline_stage; None = disabled
    num_nodes: int

    @property
    def num_gpus(self) -> int:
        return self.num_nodes * GPUS_PER_NODE

    @property
    def dp(self) -> int:
        return self.num_gpus // (self.tp * self.pp)

    @property
    def num_layers(self) -> int:
        return NUM_LAYERS

    @property
    def grad_accum_steps(self) -> int:
        return GLOBAL_BATCH_SIZE // (self.mbs * self.dp)

    def label(self) -> str:
        vpp_str = f"vpp={self.num_layers // (self.pp * self.vpp)}" if self.vpp else "vpp=off"
        rc_str = "rc" if self.recompute else "no-rc"
        sp_str = "sp" if self.sp else "no-sp"
        return f"tp{self.tp}-pp{self.pp}-{sp_str}-{rc_str}-mbs{self.mbs}-{vpp_str}-{self.num_nodes}n"


def _vpp_display(pt: SweepPoint) -> str:
    if pt.vpp is None:
        return "-"
    return str(pt.num_layers // (pt.pp * pt.vpp))


# ---------------------------------------------------------------------------
# Build full sweep
# ---------------------------------------------------------------------------


def build_sweep(
    tp_values: list[int],
    pp_values: list[int],
    node_counts: list[int],
    recompute_values: list[bool],
    mbs_values: list[int],
    vpp_stages: list[Optional[int]],
) -> list[SweepPoint]:
    points: list[SweepPoint] = []
    for num_nodes in node_counts:
        num_gpus = num_nodes * GPUS_PER_NODE
        for tp in tp_values:
            for pp in pp_values:
                if num_gpus % (tp * pp) != 0:
                    continue
                dp = num_gpus // (tp * pp)
                sp_options = [True, False] if tp > 1 else [False]
                for sp in sp_options:
                    for recompute in recompute_values:
                        for mbs in mbs_values:
                            # global-batch-size must be divisible by (mbs * dp)
                            if GLOBAL_BATCH_SIZE % (mbs * dp) != 0:
                                continue
                            vpp_options: list[Optional[int]] = [None]
                            # PP>2, not PP>1: with overlap_p2p_comm=false (which this
                            # whole sweep uses, matched to the traces) Megatron refuses
                            # the interleaved schedule outright --
                            #   "When interleaved schedule is used and p2p communication
                            #    overlap is disabled, pipeline-model-parallel size should
                            #    be greater than 2 to avoid having multiple p2p sends and
                            #    recvs between same 2 ranks per communication batch"
                            # Emitting VPP at PP=2 would rank configs that cannot be run
                            # on hardware (measured: jobs 977783/977784 both aborted on
                            # this assert). Verified 2026-07-19.
                            if pp > 2:
                                for n in vpp_stages:
                                    if n is not None and NUM_LAYERS % (pp * n) == 0:
                                        vpp_options.append(n)
                            for vpp in vpp_options:
                                points.append(SweepPoint(
                                    tp=tp, pp=pp, sp=sp, recompute=recompute,
                                    mbs=mbs, vpp=vpp, num_nodes=num_nodes,
                                ))
    return points


