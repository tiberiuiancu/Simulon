def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--tp", nargs="+", type=int, default=[2, 4],
                   help="TP values (default: 2 4)")
    p.add_argument("--pp", nargs="+", type=int, default=[1, 2],
                   help="PP values (default: 1 2)")
    p.add_argument("--nodes", nargs="+", type=int, default=[16],
                   help="num_nodes values (default: 16)")
    p.add_argument("--gbs", type=int, default=GLOBAL_BATCH_SIZE,
                   help=f"global-batch-size, fixed across the sweep (default: {GLOBAL_BATCH_SIZE})")
    p.add_argument("--recompute", nargs="+", type=lambda x: x.lower() == "true",
                   default=[False, True], metavar="true|false",
                   help="recompute-activations values (default: false true)")
    p.add_argument("--mbs", nargs="+", type=int, default=[1, 2, 4, 6, 8],
                   metavar="N",
                   help="micro-batch-size values (default: 1 2 4 6 8); "
                        f"invalid combos where gbs={GLOBAL_BATCH_SIZE} %% (mbs*dp) != 0 are skipped")
    p.add_argument("--vpp-stages", nargs="+", type=int, default=[],
                   metavar="N",
                   help="num_layers_per_virtual_pipeline_stage values when PP>1 "
                        "(default: none — VPP disabled)")
    p.add_argument("--out", type=Path, default=None,
                   help="Save results as JSON to this path")
    p.add_argument("--derive-low-pp", action="store_true",
                   help="Fill PP={1,2} configs that lack a trace (OOM) by deriving "
                        "from the tp{tp}pp4 trace (pp_synth). Rows are flagged "
                        "UNVALIDATED — gate with validate_pp_derive.py first.")
    p.add_argument("--verbose", action="store_true",
                   help="Print per-point progress")
    return p.parse_args()


def main() -> None:
    args = parse_args()

    # Override the fixed global-batch-size for this sweep (module global is read
    # by SweepPoint.grad_accum_steps, build_sweep and build_scenario).
    global GLOBAL_BATCH_SIZE, DERIVE_LOW_PP
    GLOBAL_BATCH_SIZE = args.gbs
    DERIVE_LOW_PP = args.derive_low_pp

    vpp_stages_with_none: list[Optional[int]] = [None] + args.vpp_stages

    points = build_sweep(
        tp_values=args.tp,
        pp_values=args.pp,
        node_counts=args.nodes,
        recompute_values=args.recompute,
        mbs_values=args.mbs,
        vpp_stages=vpp_stages_with_none,
    )

    print(f"Sweep: {len(points)} configs total")

    results: list[SimResult] = []
    for i, pt in enumerate(points, 1):
        if args.verbose:
            print(f"  [{i}/{len(points)}] {pt.label()} ...", end=" ", flush=True)
        r = simulate_point(pt)
        results.append(r)
        if args.verbose:
            if r.status == "ok":
                mfu = f"  {r.mfu_pct:.1f}% MFU" if r.mfu_pct else ""
                print(f"{r.per_gpu_tps:.0f} tps/GPU{mfu}")
            else:
                print(r.status)

    print_table(results)

    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        with open(args.out, "w") as f:
            json.dump([r.to_dict() for r in results], f, indent=2)
        print(f"Results saved to {args.out}")


if __name__ == "__main__":
    main()
