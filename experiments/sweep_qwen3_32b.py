# Recompute overhead model. The sweep's `recompute-activations` flag is Megatron
# *selective* recompute (core attention re-run in bwd) — its cost is not cleanly
# extractable from the non-recompute trace, so it is calibrated from a matched
# A/B pair (same container, recompute the only delta).
#
# CALIBRATED from a matched nemo_26.04.sif A/B (PP=1, TP=4, SP=true, mbs=1,
# gbs=256, 16 nodes):
#     no-recompute  11,214.0 ms / 304.1 TF/s/GPU   (slurm-906264)
#     selective rc  11,516.9 ms / 296.1 TF/s/GPU   (slurm-906258)
#     overhead = 11516.9/11214.0 - 1 = +2.70% wall time
# (An earlier attempt was container-confounded — recompute under nemo vs baselines
# under MegatronTraining — and is discarded.)
#
# The model adds `factor * compute_ms` to wall time, so the compute-fraction
# factor that reproduces a +2.70% wall increase is
#     0.0270 * (base_total/base_compute) = 0.0270 * (11068.5/7111.4) = 0.042.
# RECALIBRATED 2026-07-19 at SP=false (job 977786). The +2.70% figure above came
# from an SP=TRUE A/B — the configuration whose traces are invalid — and understates
